// จับคู่โพสต์กับวัตถุดิบที่มี เรียงจากตรงมากสุด
export function matchPosts(posts, ingredients, prompt = '') {
  const have = ingredients.map((s) => s.trim().toLowerCase()).filter(Boolean);
  const hit = (name) => {
    const n = name.toLowerCase();
    return have.some((h) => n.includes(h) || h.includes(n));
  };
  const kws = prompt.toLowerCase().split(/[\s,]+/).filter(Boolean);

  return posts
    .filter((p) => p.main && p.main.length > 0)
    .map((p) => {
      const found = p.main.filter(hit);
      const missing = p.main.filter((m) => !hit(m));
      const tagHit = kws.some((k) =>
        (p.tags || []).some((t) => t.toLowerCase().includes(k) || k.includes(t.toLowerCase()))
      );
      return { post: p, found, missing, score: (found.length / p.main.length) * 10 + (tagHit ? 3 : 0) };
    })
    .filter((m) => m.found.length > 0)
    .sort((a, b) => b.score - a.score);
}
